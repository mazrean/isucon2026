// Command signgen generates sign_avx512_amd64.s: a 16-lane AVX-512 kernel
// that advances 16 independent HMAC-SHA256 chains (value = HMAC(key, value))
// where every message is exactly one 32-byte digest.
//
//	go run ./internal/signgen > sign_avx512_amd64.s
package main

import (
	"fmt"
	"os"
	"strings"
)

var k256 = [64]uint32{
	0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4, 0xab1c5ed5,
	0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3, 0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174,
	0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f, 0x4a7484aa, 0x5cb0a9dc, 0x76f988da,
	0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7, 0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967,
	0x27b70a85, 0x2e1b2138, 0x4d2c6dfc, 0x53380d13, 0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85,
	0xa2bfe8a1, 0xa81a664b, 0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070,
	0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3,
	0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2,
}

var b strings.Builder

func emit(format string, args ...any) { fmt.Fprintf(&b, "\t"+format+"\n", args...) }

func z(i int) string { return fmt.Sprintf("Z%d", i) }

func main() {
	b.WriteString("// Code generated by internal/signgen; DO NOT EDIT.\n\n#include \"textflag.h\"\n\n")
	for i, k := range k256 {
		fmt.Fprintf(&b, "DATA signK<>+%d(SB)/4, $0x%08x\n", i*4, k)
	}
	b.WriteString("GLOBL signK<>(SB), RODATA|NOPTR, $256\n\n")
	b.WriteString("DATA signPad<>+0(SB)/4, $0x80000000\nDATA signPad<>+4(SB)/4, $0x00000300\nGLOBL signPad<>(SB), RODATA|NOPTR, $8\n\n")

	// func chainAVX512(st *chainState, n int)
	// chainState: ist [8][16]uint32 @0, ost @512, v @1024. n = number of HMAC rounds.
	b.WriteString("// func chainAVX512(st *chainState, n int)\nTEXT ·chainAVX512(SB), NOSPLIT, $0-16\n")
	emit("MOVQ st+0(FP), DI")
	emit("MOVQ n+8(FP), CX")
	emit("SHLQ $1, CX") // two compressions per HMAC round
	emit("LEAQ 0(DI), R8")
	emit("LEAQ 512(DI), R9")
	// W ring Z8..Z23; load v into W0..W7.
	for j := 0; j < 8; j++ {
		emit("VMOVDQU32 %d(DI), %s", 1024+64*j, z(8+j))
	}
	b.WriteString("loop:\n")
	// fixed padding words W8..W15
	emit("VPBROADCASTD signPad<>+0(SB), %s", z(16))
	for j := 9; j < 15; j++ {
		emit("VPXORD %s, %s, %s", z(8+j), z(8+j), z(8+j))
	}
	emit("VPBROADCASTD signPad<>+4(SB), %s", z(23))
	// state a..h = Z0..Z7 loaded from midstate at R8
	for j := 0; j < 8; j++ {
		emit("VMOVDQU32 %d(R8), %s", 64*j, z(j))
	}
	reg := [8]int{0, 1, 2, 3, 4, 5, 6, 7} // a..h
	w := func(t int) string { return z(8 + t%16) }
	for t := 0; t < 64; t++ {
		if t >= 16 {
			// W[t] = W[t-16] + s0(W[t-15]) + W[t-7] + s1(W[t-2])
			x, y := w(t-15), w(t-2)
			emit("VPRORD $7, %s, Z27", x)
			emit("VPRORD $18, %s, Z28", x)
			emit("VPSRLD $3, %s, Z29", x)
			emit("VPTERNLOGD $0x96, Z29, Z28, Z27")
			emit("VPRORD $17, %s, Z28", y)
			emit("VPRORD $19, %s, Z29", y)
			emit("VPSRLD $10, %s, Z30", y)
			emit("VPTERNLOGD $0x96, Z30, Z29, Z28")
			emit("VPADDD Z27, %s, %s", w(t), w(t))
			emit("VPADDD Z28, %s, %s", w(t), w(t))
			emit("VPADDD %s, %s, %s", w(t-7), w(t), w(t))
		}
		a, bb, c, d, e, f, g, h := z(reg[0]), z(reg[1]), z(reg[2]), z(reg[3]), z(reg[4]), z(reg[5]), z(reg[6]), z(reg[7])
		emit("VPADDD %s, %s, %s", w(t), h, h)
		emit("VPADDD.BCST signK<>+%d(SB), %s, %s", t*4, h, h)
		emit("VPRORD $6, %s, Z24", e)
		emit("VPRORD $11, %s, Z25", e)
		emit("VPRORD $25, %s, Z26", e)
		emit("VPTERNLOGD $0x96, Z26, Z25, Z24")
		emit("VMOVDQA32 %s, Z25", e)
		emit("VPTERNLOGD $0xca, %s, %s, Z25", g, f) // e ? f : g
		emit("VPADDD Z24, %s, %s", h, h)
		emit("VPADDD Z25, %s, %s", h, h)   // h = T1
		emit("VPADDD %s, %s, %s", h, d, d) // d = d + T1
		emit("VPRORD $2, %s, Z24", a)
		emit("VPRORD $13, %s, Z25", a)
		emit("VPRORD $22, %s, Z26", a)
		emit("VPTERNLOGD $0x96, Z26, Z25, Z24")
		emit("VMOVDQA32 %s, Z25", a)
		emit("VPTERNLOGD $0xe8, %s, %s, Z25", c, bb) // maj(a,b,c)
		emit("VPADDD Z24, %s, %s", h, h)
		emit("VPADDD Z25, %s, %s", h, h) // h = T1 + T2
		reg = [8]int{reg[7], reg[0], reg[1], reg[2], reg[3], reg[4], reg[5], reg[6]}
	}
	// digest = state + midstate -> W0..W7 (message of the next compression)
	for j := 0; j < 8; j++ {
		emit("VPADDD %d(R8), %s, %s", 64*j, z(reg[j]), z(8+j))
	}
	emit("XCHGQ R8, R9")
	emit("DECQ CX")
	emit("JNZ loop")
	for j := 0; j < 8; j++ {
		emit("VMOVDQU32 %s, %d(DI)", z(8+j), 1024+64*j)
	}
	emit("VZEROUPPER")
	emit("RET")
	b.WriteString("\n// func cpuHasAVX512() bool\nTEXT ·cpuHasAVX512(SB), NOSPLIT, $0-1\n")
	emit("MOVB $0, ret+0(FP)")
	emit("MOVL $0, AX")
	emit("CPUID")
	emit("CMPL AX, $7")
	emit("JLT no")
	emit("MOVL $1, AX")
	emit("MOVL $0, CX")
	emit("CPUID")
	emit("BTL $27, CX") // OSXSAVE
	emit("JCC no")
	emit("MOVL $7, AX")
	emit("MOVL $0, CX")
	emit("CPUID")
	emit("BTL $16, BX") // AVX512F
	emit("JCC no")
	emit("MOVL $0, CX")
	emit("XGETBV")
	emit("ANDL $0xe6, AX") // XMM|YMM|opmask|ZMM_Hi256|Hi16_ZMM
	emit("CMPL AX, $0xe6")
	emit("JNE no")
	emit("MOVB $1, ret+0(FP)")
	b.WriteString("no:\n")
	emit("RET")
	os.Stdout.WriteString(b.String())
}
